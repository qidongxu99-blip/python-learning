"""
第一个 Python 小练习：互动式自我介绍
=====================================
这个小程序会问你名字和年龄，然后跟你打招呼。

你会学到这些核心概念：
1. print()   —— 让电脑在屏幕上打印一句话
2. input()   —— 让用户从键盘敲东西进来
3. 变量       —— 像贴了标签的盒子，里面装着数据
4. int()     —— 把文字转成数字
5. f-string  —— 在字符串里嵌变量的方法
6. 算术运算   —— 加减乘除
7. if/else   —— 条件判断（如果...否则...）
8. 字符串拼接 —— 把几段文字拼到一起

怎么运行：
    在终端里输入：python3 hello_intro.py
    然后跟着提示敲字就行。
"""


# ---------- 1. 输出：print() ----------
# print() 就是让电脑在屏幕上打印一句话
# "*" * 30 表示把星号重复 30 次，拼成一条分隔线
print("=" * 30)
print("  你好，我是你的第一个 Python 程序")
print("=" * 30)


# ---------- 2. 输入和变量：input() ----------
# input("提示语") 会在屏幕上显示提示语，然后等你敲字、按回车
# 你敲的内容会被存进 name 这个变量里
# 变量你可以理解成：一个贴了标签的盒子，盒子里装着数据
name = input("请输入你的名字：")

# input() 收到的内容，永远默认是"文字"（字符串）
# 但年龄要做算术，得先转成数字，所以套一层 int()
# int 是 integer（整数）的缩写
age = int(input("请输入你的年龄："))


# ---------- 3. f-string 格式化 ----------
# 在字符串前面加个 f，就能用 {变量名} 把变量的值嵌进去
# 比如这里的 {name} 会被替换成你输入的名字
print(f"\n你好 {name}！")
print(f"你今年 {age} 岁。")


# ---------- 4. 算术运算 ----------
# 用当前年份减去年龄，估算你出生的年份
# 2026 是当前的公历年份
birth_year = 2026 - age
print(f"照这么算，你大概出生在 {birth_year} 年。")


# ---------- 5. 字符串拼接和重复 ----------
# + 可以把几段文字拼到一起
# * 可以把一段文字重复若干次（"加油学习 " * 3 就是重复 3 次）
print("\n" + "加油学习 " * 3 + "!")


# ---------- 6. 条件判断：if / else ----------
# if 后面跟一个条件，满足就执行 if 下面的代码
# 不满足就跳到 else，执行 else 下面的代码
# 注意：if 和 else 下面的行都要往里缩进 4 个空格，这是 Python 的规矩
if age >= 18:
    print("你已经成年啦，大学生活精彩着呢！")
else:
    print("你还没成年，趁年轻多学点东西~")


# ---------- 收尾 ----------
print("\n--- 程序结束 ---")
